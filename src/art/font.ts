export const FONT: Record<string, boolean[][]> = {};
for (const [ch, s] of Object.entries(G)) {
  FONT[ch] = s.split('|').map((r) => r.padEnd(5, '.').slice(0, 5).split('').map((c) => c === '#'));
}

export const GLYPH_W = 6; // advance incl. spacing
export const GLYPH_H = 8;

export function textWidth(s: string, scale = 1): number {
  return s.length ? (s.length * GLYPH_W - 1) * scale : 0;
}
